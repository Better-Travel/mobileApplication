package com.bettertravel.localization.generator

import java.io.File
import javax.xml.parsers.DocumentBuilderFactory

private const val DEFAULT_LANGUAGE = "en"

fun main(args: Array<String>) {
    val stringsDir = File(args[0])
    val outputFile = File(args[1])
    val languages =
        stringsDir
            .listFiles { file -> file.isDirectory }
            .orEmpty()
            .map { it.name }
            .sorted()
    val byLanguage = languages.associateWith { language -> readStrings(File(stringsDir, "$language/strings.xml")) }
    val defaults = byLanguage.getValue(DEFAULT_LANGUAGE)
    outputFile.parentFile.mkdirs()
    outputFile.writeText(render(defaults.keys.toList(), languages, byLanguage))
}

private fun readStrings(file: File): Map<String, String> {
    val document = DocumentBuilderFactory.newInstance().newDocumentBuilder().parse(file)
    val nodes = document.getElementsByTagName("string")
    val result = linkedMapOf<String, String>()
    for (index in 0 until nodes.length) {
        val node = nodes.item(index)
        result[node.attributes.getNamedItem("name").nodeValue] = node.textContent
    }
    return result
}

private fun render(
    keys: List<String>,
    languages: List<String>,
    byLanguage: Map<String, Map<String, String>>,
): String {
    val builder = StringBuilder()
    builder.appendLine("// Generated by :localization:generator:generateKotlinFromXml. Do not edit.")
    builder.appendLine("package com.bettertravel.localization")
    builder.appendLine()
    builder.appendLine("interface StringRepository {")
    keys.forEach { key -> builder.appendLine("    val ${camel(key)}: String") }
    builder.appendLine("}")
    builder.appendLine()
    builder.appendLine("class GeneratedStringRepository(")
    builder.appendLine("    private val languageCode: () -> String,")
    builder.appendLine(") : StringRepository {")
    keys.forEach { key ->
        builder.appendLine("    override val ${camel(key)}: String")
        builder.appendLine("        get() {")
        builder.appendLine("            return when (languageCode()) {")
        languages.filter { it != DEFAULT_LANGUAGE }.forEach { language ->
            val value = byLanguage.getValue(language)[key] ?: byLanguage.getValue(DEFAULT_LANGUAGE).getValue(key)
            builder.appendLine("                \"$language\" -> \"${escape(value)}\"")
        }
        builder.appendLine("                else -> \"${escape(byLanguage.getValue(DEFAULT_LANGUAGE).getValue(key))}\"")
        builder.appendLine("            }")
        builder.appendLine("        }")
        builder.appendLine()
    }
    builder.setLength(builder.length - 1)
    builder.appendLine("}")
    return builder.toString()
}

private fun camel(key: String): String {
    val parts = key.split("_")
    return parts.first() + parts.drop(1).joinToString("") { part -> part.replaceFirstChar { it.uppercase() } }
}

private fun escape(value: String): String {
    return value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
}
